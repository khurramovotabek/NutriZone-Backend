def _resolve(english: str, key: str) -> str:
    lang = (translation.get_language() or "uz")[:2]
    pair = LABELS[key]
    if lang == "uz":
        return pair[0]
    if lang == "ru":
        return pair[1]
    return english


_lazy_resolve = lazy(_resolve, str)


def localized(text):
    """A lazy uz/ru version of `text` when it is an English label we know and no .po catalog translates it; otherwise `text` unchanged."""
    if text is None:
        return text
    if not isinstance(text, str):
        # gettext_lazy / format_lazy: keep it when the uz catalog really translates it
        with translation.override("uz"):
            as_uz = str(text)
        with translation.override("en"):
            as_en = str(text)
        if as_uz != as_en:
            return text
        text = as_en
    key = text.strip().lower()
    return _lazy_resolve(text, key) if key in LABELS else text


def install() -> None:
    if any(cmd in sys.argv for cmd in ("makemigrations", "squashmigrations", "migrate", "sqlmigrate")):
        return
    from django.apps import apps

    for model in apps.get_models():
        meta = model._meta
        for attr in ("verbose_name_plural", "verbose_name"):  # plural first: Django derives it lazily from verbose_name
            setattr(meta, attr, localized(getattr(meta, attr)))
        for field in [*meta.local_fields, *meta.local_many_to_many]:
            field.verbose_name = localized(field.verbose_name)
            if field.choices:
                field.choices = [_localize_choice(c) for c in field.choices]


def install_admin_descriptions() -> None:
    """Column headers and action names (`short_description`) of every registered ModelAdmin and inline; run once the admin registry is complete."""
    from django.contrib import admin

    seen = set()
    for model_admin in list(admin.site._registry.values()):
        for cls in (type(model_admin), *getattr(model_admin, "inlines", ())):
            for klass in cls.__mro__:
                if klass in seen or klass.__module__.startswith("django."):
                    continue
                seen.add(klass)
                for value in vars(klass).values():
                    func = getattr(value, "__func__", value)
                    if callable(func) and isinstance(getattr(func, "short_description", None), str):
                        func.short_description = localized(func.short_description)


def _localize_choice(choice):
    value, label = choice
    if isinstance(label, (list, tuple)):  # optgroup
        return value, [_localize_choice(c) for c in label]
    return value, localized(label)
