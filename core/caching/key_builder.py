"""
CacheKeyBuilder -- namespaced, versioned cache keys.

Extends core/caching/redis_client.py's simple `cache_key()` helper with
two enterprise requirements the mission calls out specifically:

  - Namespacing per domain (product/search/store/wallet/analytics), so
    a bulk `invalidate_namespace()` (e.g. "clear every cached product
    page") doesn't need to enumerate every individual key.
  - Versioned keys, so a breaking change to a cached payload's shape
    (e.g. ProductCard gains a new field) can be rolled out by bumping
    one version number rather than needing an explicit cache flush --
    old-version keys simply age out via TTL and are never read again.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from core.caching.redis_client import get_redis_client

_VERSION_KEY_PREFIX = "nutrizone:cache-version"


class CacheDomain:
    """
    The domain namespaces the mission explicitly names. A closed list
    (like FlagKey) rather than an arbitrary string, so a typo'd domain
    name fails fast rather than silently creating an orphaned
    namespace nothing ever invalidates.
    """

    PRODUCT = "product"
    SEARCH = "search"
    STORE = "store"
    WALLET = "wallet"
    ANALYTICS = "analytics"


_ALL_DOMAINS = frozenset(
    {CacheDomain.PRODUCT, CacheDomain.SEARCH, CacheDomain.STORE, CacheDomain.WALLET, CacheDomain.ANALYTICS}
)


@dataclass(frozen=True, slots=True)
class CacheKeyBuilder:
    """
    Usage:
        keys = CacheKeyBuilder(domain=CacheDomain.PRODUCT)
        key = keys.build("detail", product_id)          # versioned, namespaced key
        keys.bump_version()                               # invalidate every PRODUCT key at once
    """

    domain: str

    def __post_init__(self) -> None:
        if self.domain not in _ALL_DOMAINS:
            raise ValueError(f"Unknown cache domain '{self.domain}'. Must be one of {sorted(_ALL_DOMAINS)}.")

    def _version(self) -> int:
        """
        Defaults to 0 (not 1) for a domain with no version key yet --
        this must match what `client.incr()` produces on its own first
        call against a nonexistent key (Redis INCR: missing key -> 1),
        or the very first `bump_version()` for a domain is a silent
        no-op: `_version()` would already report 1 by default, and
        INCR's first result is also 1, so no key generated by `build()`
        would actually change. Confirmed directly against a real Redis
        instance before this fix (`GET` on a fresh key -> nil, `INCR`
        on the same fresh key -> 1 -- identical to the old default).
        """
        client = get_redis_client()
        raw = client.get(f"{_VERSION_KEY_PREFIX}:{self.domain}")
        return int(raw) if raw is not None else 0

    def bump_version(self) -> int:
        """Invalidates every key ever built for this domain, without a scan/delete."""
        client = get_redis_client()
        return client.incr(f"{_VERSION_KEY_PREFIX}:{self.domain}")

    def build(self, *parts: Any) -> str:
        version = self._version()
        joined = ":".join(str(p) for p in parts)
        return f"nutrizone:{self.domain}:v{version}:{joined}"
